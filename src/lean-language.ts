export function registerLean(monaco: {
  languages: Pick<
    typeof Monaco.languages,
    'getLanguages' | 'register' | 'setLanguageConfiguration' | 'setMonarchTokensProvider'
  >;
}): void {
  if (monaco.languages.getLanguages().some((language) => language.id === LEAN_LANGUAGE_ID)) return;

  monaco.languages.register({
    id: LEAN_LANGUAGE_ID,
    extensions: ['.lean'],
    aliases: ['Lean 4', 'lean'],
  });

  monaco.languages.setLanguageConfiguration(LEAN_LANGUAGE_ID, {
    comments: { lineComment: '--', blockComment: ['/-', '-/'] },
    brackets: [
      ['(', ')'],
      ['[', ']'],
      ['{', '}'],
      ['⟨', '⟩'],
    ],
    autoClosingPairs: [
      { open: '(', close: ')' },
      { open: '[', close: ']' },
      { open: '{', close: '}' },
      { open: '⟨', close: '⟩' },
      { open: '"', close: '"', notIn: ['string'] },
    ],
    surroundingPairs: [
      { open: '(', close: ')' },
      { open: '[', close: ']' },
      { open: '{', close: '}' },
      { open: '⟨', close: '⟩' },
      { open: '"', close: '"' },
    ],
  });

  monaco.languages.setMonarchTokensProvider(LEAN_LANGUAGE_ID, {
    defaultToken: '',
    tokenPostfix: '.lean',
    keywords: KEYWORDS,
    tactics: TACTICS,
    operators: [
      '=',
      ':=',
      '=>',
      '→',
      '←',
      '↔',
      '∧',
      '∨',
      '¬',
      '∀',
      '∃',
      'λ',
      '≤',
      '≥',
      '≠',
      '+',
      '-',
      '*',
      '/',
      '^',
      '∘',
    ],
    tokenizer: {
      root: [
        [/\/-/, 'comment', '@comment'],
        [/--.*$/, 'comment'],
        [/r#"/, 'string', '@rawstring'],
        [/"([^"\\]|\\.)*"/, 'string'],
        [/'([^'\\]|\\.)'/, 'string.char'],
        [/\b\d+(\.\d+)?\b/, 'number'],
        [
          /[A-Za-z_\u00C0-\uFFFF][\w'!?\u00C0-\uFFFF]*/,
          {
            cases: {
              '@keywords': 'keyword',
              '@tactics': 'keyword.control',
              '@default': 'identifier',
            },
          },
        ],
        [/[{}()\]⟨⟩]/, '@brackets'],
        [/[=<>+\-*/%^&|!~:]+/, 'operator'],
        [/[;,.]/, 'delimiter'],
        [/\s+/, 'white'],
      ],
      comment: [
        [/\/-/, 'comment', '@push'],
        [/-\//, 'comment', '@pop'],
        [/[^/-]+/, 'comment'],
        [/[/-]/, 'comment'],
      ],
      rawstring: [
        [/"#/, 'string', '@pop'],
        [/./, 'string'],
      ],
    },
  });
}
